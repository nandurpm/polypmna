#!/usr/bin/env node

/*
 * ============================================================
 * FILE: generate-ai-health-report.mjs
 * PURPOSE: Runs provider monitoring and writes a timestamped Markdown health report for CI artifacts.
 * ============================================================
 */

import { mkdir, writeFile } from "node:fs/promises";
import { spawn } from "node:child_process";

const startedAt = new Date();
const reportDir = "reports";
const filename = `${reportDir}/ai-provider-health-${startedAt.toISOString().slice(0, 10)}.md`;

const child = spawn(process.execPath, ["scripts/monitor-ai-providers.mjs", "both"], {
  env: { ...process.env },
});
let output = "";
let errors = "";
child.stdout.on("data", (chunk) => { output += chunk.toString(); });
child.stderr.on("data", (chunk) => { errors += chunk.toString(); });
const exitCode = await new Promise((resolve) => child.on("close", resolve));

const rows = output
  .split(/\r?\n/)
  .filter(Boolean)
  .map((line) => {
    try { return JSON.parse(line); } catch { return null; }
  })
  .filter((item) => item && item.provider);
const summary = rows.find((item) => item.summary)?.summary;
const providers = rows.filter((item) => item.status && item.provider);
const statusLabel = providers.length > 0 && providers.every((item) => item.status === "ok") ? "Healthy" : "Attention required";

const table = providers.length > 0
  ? providers.map((item) => `| ${item.provider} | ${item.model || "—"} | ${item.status} | ${item.durationMs ? `${item.durationMs} ms` : "—"} | ${item.httpStatus || "—"} |`).join("\n")
  : "| — | — | no measurement | — | — |";

const report = `# POLY PMNA AI provider health report

Generated: ${startedAt.toISOString()}

## Overall status: ${statusLabel}

This report is generated by the weekly secret-safe provider probe. It records provider metadata and timing only; it does not store API keys, prompts, or answer content.

| Provider | Model | Status | Duration | HTTP status |
|---|---|---|---:|---:|
${table}

## Measurement summary

| Field | Value |
|---|---:|
| Providers measured | ${summary?.measured ?? providers.length} |
| Healthy measurements | ${summary?.healthy ?? providers.filter((item) => item.status === "ok").length} |
| Failed measurements | ${summary?.failed ?? providers.filter((item) => item.status !== "ok").length} |
| Probe timeout | ${summary?.timeoutMs ?? process.env.AI_MONITOR_TIMEOUT_MS ?? 30000} ms |
| Browser deadline reference | ${summary?.browserDeadlineMs ?? 100000} ms |
| Monitor process exit | ${exitCode} |

## Interpretation

An \`ok\` result means the endpoint returned a non-empty assistant message within the probe timeout. A \`timeout\`, HTTP error, or \`empty\` result is intentionally treated as unhealthy so the report cannot hide a provider that is reachable but unusable. OpenRouter model routing can still select a different upstream provider behind a model candidate; the reported model is the model identifier returned by the endpoint.

${errors.trim() ? `## Monitor diagnostics\n\nThe monitor emitted a non-secret diagnostic on stderr:\n\n${errors.trim()}\n` : ""}
`;

await mkdir(reportDir, { recursive: true });
await writeFile(filename, report);
console.log(`Wrote ${filename}`);
